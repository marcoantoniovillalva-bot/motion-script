// One-off generator: base64-embeds the local caption fonts directly into a TS module so the
// browser never needs a network fetch for them during rendering (avoids font-loading stalls
// under concurrent Remotion render tabs). Re-run this if the font files in public/fonts/ change.
import { readFile, writeFile } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const fonts = [
  { name: 'Montra', file: 'Montra.otf', mime: 'font/otf' },
  { name: 'Freehand', file: 'Freehand.ttf', mime: 'font/ttf' },
  { name: 'Pacifico', file: 'Pacifico.ttf', mime: 'font/ttf' },
  { name: 'LobsterTwo', file: 'LobsterTwo-Bold.ttf', mime: 'font/ttf' },
  { name: 'LobsterTwoItalic', file: 'LobsterTwo-BoldItalic.ttf', mime: 'font/ttf' },
  { name: 'Lobster', file: 'Lobster-Regular.ttf', mime: 'font/ttf' },
];

const entries = await Promise.all(
  fonts.map(async (f) => {
    const bytes = await readFile(path.join(root, 'public', 'fonts', f.file));
    const b64 = bytes.toString('base64');
    return `export const ${f.name.toUpperCase()}_DATA_URI = 'data:${f.mime};base64,${b64}';`;
  }),
);

const out = `// AUTO-GENERATED by scripts/generate-font-data.mjs — do not edit by hand.\n${entries.join('\n')}\n`;
await writeFile(path.join(root, 'src', 'talking-head-fonts-data.ts'), out, 'utf-8');
console.log('Written src/talking-head-fonts-data.ts');
